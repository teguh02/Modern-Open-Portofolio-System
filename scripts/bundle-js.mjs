// Bundles vendor JS + fonts into public/assets/ so the app never loads scripts
// from a CDN (locked stack decision).
//
// Alpine is the CSP-safe build (@alpinejs/csp) because our CSP forbids
// 'unsafe-eval' and inline expressions. All component behaviour lives in
// resources/js/components.js and is registered through Alpine.data().
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

async function copy(from, to) {
  await mkdir(dirname(to), { recursive: true });
  await copyFile(resolve(from), resolve(to));
  console.log(`copied ${from} -> ${to}`);
}

const fonts = [
  ['@fontsource/inter/files/inter-latin-400-normal.woff2', 'inter-400.woff2'],
  ['@fontsource/inter/files/inter-latin-600-normal.woff2', 'inter-600.woff2'],
  ['@fontsource/fraunces/files/fraunces-latin-500-normal.woff2', 'fraunces-500.woff2'],
  ['@fontsource/fraunces/files/fraunces-latin-600-normal.woff2', 'fraunces-600.woff2'],
  ['@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff2', 'jetbrains-mono-400.woff2'],
  ['@fontsource/jetbrains-mono/files/jetbrains-mono-latin-500-normal.woff2', 'jetbrains-mono-500.woff2'],
];

for (const [from, name] of fonts) {
  try {
    await copy(`node_modules/${from}`, `public/assets/fonts/${name}`);
  } catch (error) {
    console.warn(`font skipped (${name}): ${error.message}`);
  }
}

// app.js = CSP-safe Alpine + MOPS components concatenated (concatenation is
// enough: Alpine exposes window.Alpine and components.js listens for
// alpine:init, so no bundler is required).
const alpine = await readFile(resolve('node_modules/@alpinejs/csp/dist/cdn.min.js'), 'utf8');
const components = await readFile(resolve('resources/js/components.js'), 'utf8');
const banner = '/* MOPS bundle: @alpinejs/csp + components. Generated by npm run build:js */\n';

await mkdir('public/assets/js', { recursive: true });
await writeFile(resolve('public/assets/js/app.js'), `${banner}${alpine}\n${components}`);
console.log('built public/assets/js/app.js');
